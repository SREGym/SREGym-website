function rawLines(value, columns) {
  const lines = [];
  let remaining = value;
  while (remaining.length > columns) {
    const chunk = remaining.slice(0, columns + 1);
    let end = chunk.lastIndexOf(" ");
    if (end < columns / 2) end = Math.max(chunk.lastIndexOf(","), chunk.lastIndexOf(";"));
    if (end < columns / 2) end = columns - 1;
    lines.push(remaining.slice(0, end + 1));
    remaining = remaining.slice(end + 1);
  }
  if (remaining) lines.push(remaining);
  assert.equal(lines.join(""), value);
  return lines;
}

