const escape = (value) => String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");

function estimatedWidth(value, size) {
  return [...value].reduce((sum, char) => sum + (/[ilI1.,':;!|]/.test(char) ? 0.29 : /[MW@%]/.test(char) ? 0.91 : /[A-Z]/.test(char) ? 0.7 : 0.54), 0) * size;
}

function wrap(value, width, size) {
  const lines = [];
  let line = "";
  for (const word of value.split(" ")) {
    if (line && estimatedWidth(`${line} ${word}`, size) > width) {
      lines.push(line);
      line = "";
    }
    line += (line ? " " : "") + word;
  }
  if (line) lines.push(line);
  return lines;
}

class Drawing {
  constructor(mobile, title, subtitle = "") {
    this.mobile = mobile;
    this.width = mobile ? 440 : 1200;
    this.margin = mobile ? 16 : 44;
    this.title = title;
    this.parts = [];
    const size = mobile ? 25 : 30;
    let y = mobile ? 36 : 48;
    y = this.paragraph(this.margin, y, title, this.width - 2 * this.margin, { size, color: "title", bold: true });
    if (subtitle) y = this.paragraph(this.margin, y + 5, subtitle, this.width - 2 * this.margin, { size: mobile ? 18 : 20, color: "muted" });
    this.top = y + 25;
  }

  text(x, y, value, { size = 22, color = "ink", bold = false, anchor = "start", mono = false } = {}) {
    assert.ok(y >= size && x >= 0 && x <= this.width, `Text outside ${this.title}: ${value}`);
    this.parts.push(`<text x="${x}" y="${y}" fill="var(--${color})" font-size="${size}" font-weight="${bold ? 700 : 400}" text-anchor="${anchor}"${mono ? ' class="code"' : ""}>${escape(value)}</text>`);
  }

  paragraph(x, y, value, width, options = {}) {
    const size = options.size ?? 22;
    const lines = wrap(value, width, size);
    lines.forEach((line, index) => this.text(x, y + index * Math.round(size * 1.36), line, options));
    return y + lines.length * Math.round(size * 1.36);
  }

  box(x, y, width, height, fill = "panel", edge = "line", dashed = false) {
    this.parts.push(`<rect x="${x}" y="${y}" width="${width}" height="${height}" rx="9" fill="var(--${fill})"${edge ? ` stroke="var(--${edge})" stroke-width="1.5"` : ""}${dashed ? ' stroke-dasharray="7 5"' : ""}/>`);
  }

  path(path, { color = "muted", arrow = false, dashed = false, width = 2 } = {}) {
    this.parts.push(`<path d="${path}" fill="none" stroke="var(--${color})" stroke-width="${width}" stroke-linejoin="round"${arrow ? ' marker-end="url(#arrow)"' : ""}${dashed ? ' stroke-dasharray="5 5"' : ""}/>`);
  }

  finish(height, description = this.title) {
    return { width: this.width, height, source: `<!-- Generated by scripts/blog/diagnosis-pipeline-improvements/render-figures.mjs. -->
<svg xmlns="http://www.w3.org/2000/svg" width="${this.width}" height="${height}" viewBox="0 0 ${this.width} ${height}" role="img" aria-labelledby="title description">
<title id="title">${escape(this.title)}</title>
<desc id="description">${escape(description)}</desc>
<style>${style}</style>
<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0 1L9 5L0 9Z" fill="var(--muted)"/></marker></defs>
<rect width="${this.width}" height="${height}" fill="var(--paper)"/>
${this.parts.join("\n")}
</svg>
` };
  }
}

