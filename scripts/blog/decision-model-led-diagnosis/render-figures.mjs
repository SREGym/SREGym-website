function table(headers, sections, widths, { size = 21 } = {}) {
  let y = 24;
  let body = "";
  const drawRow = (cells, header = false) => {
    const height =
      Math.max(
        ...cells.map((cell, i) => wrap(cell, widths[i] - 32, size).length),
      ) *
        size *
        1.4 +
      32;
    if (header)
      body += `<rect x="24" y="${y}" width="1152" height="${height}" fill="var(--panel)"/>`;
    let x = 24;
    cells.forEach((cell, i) => {
      let baseline = y + 16 + size;
      String(cell)
        .split("\n")
        .forEach((paragraph, lineIndex) => {
          body += lines(x + 16, baseline, paragraph, widths[i] - 32, {
            size,
            cls: lineIndex > 0 ? "muted" : header || i > 0 ? "bold" : "",
          });
          baseline += wrap(paragraph, widths[i] - 32, size).length * size * 1.4;
        });
      if (i > 0) body += `<path class="rule" d="M${x} ${y}v${height}"/>`;
      x += widths[i];
    });
    y += height;
    body += `<path class="rule" d="M24 ${y}H1176"/>`;
  };
  drawRow(headers, true);
  for (const section of sections) {
    if (section.label) {
      body += `<rect x="24" y="${y}" width="1152" height="52" fill="var(--panel)"/>`;
      body += text(40, y + 34, section.label, { size: 20, cls: "teal bold" });
      y += 52;
      body += `<path class="rule" d="M24 ${y}H1176"/>`;
    }
    section.rows.forEach((row) => drawRow(row));
  }
  body += `<rect x="24" y="24" width="1152" height="${y - 24}" fill="none" class="rule"/>`;
  return { height: Math.ceil(y + 24), body };
}

function tools() {
  let y = 90;
  let body =
    text(32, 52, "LOOKS AT", { size: 20, cls: "muted bold" }) +
    text(202, 52, "TOOL", { size: 20, cls: "muted bold" }) +
    text(492, 52, "WHAT IT SHOWS", { size: 20, cls: "muted bold" });
  let previous = "";
  for (const [group, tool, description] of data.tools) {
    const height = Math.max(60, wrap(description, 660, 23).length * 32 + 24);
    if (group !== previous) {
      body += `<path class="rule" d="M32 ${y - 16}H1168"/>`;
      body += text(32, y + 22, group, { size: 23, cls: "bold" });
    }
    body += text(202, y + 22, tool, { size: 22, cls: "mono teal" });
    body += lines(492, y + 22, description, 660, { size: 23 });
    previous = group;
    y += height;
  }
  return { height: y + 24, body };
}

function decision(item) {
  let body =
    text(40, 52, `STEP ${item.step}`, { size: 21, cls: "mono muted" }) +
    text(1160, 52, `ONE REQUEST TO JEV, ${item.latency}`, {
      size: 21,
      cls: "mono muted",
      anchor: "end",
    });
  body += `<path class="rule" d="M40 78H1160"/>`;
  body +=
    text(40, 124, "Which tool should run next?", { size: 27, cls: "bold" }) +
    text(470, 124, "top 6 of 41 options", { size: 21, cls: "mono muted" });
  const maximum = item.options[0][2];
  item.options.forEach(([tool, target, probability], i) => {
    const y = 150 + i * 65;
    if (i === 0)
      body += `<rect x="40" y="${y}" width="1120" height="58" rx="5" fill="var(--decision)" stroke="var(--teal)" stroke-width="2"/>`;
    body += text(52, y + 25, tool, { size: 23, cls: "mono teal" });
    if (target) body += text(52, y + 48, target, { size: 20 });
    body += `<rect x="585" y="${y + 24}" width="470" height="13" rx="3" fill="var(--panel)"/><rect x="585" y="${y + 24}" width="${(470 * 0.93 * probability) / maximum}" height="13" fill="var(--${i === 0 ? "teal" : "bar"})"/>`;
    body += text(1148, y + 37, Number(probability).toFixed(2), {
      size: 23,
      cls: "mono",
      anchor: "end",
    });
  });
  let y = 566;
  for (const [label, value] of [
    ["Is the last result abnormal?", item.abnormal],
    ["Is the evidence enough?", item.enough],
    [
      "Where did the fault start?",
      item.causes
        .map(([name, probability]) => `${name} ${probability}`)
        .join("\n"),
    ],
  ]) {
    body += `<path class="rule" d="M40 ${y - 30}H1160"/>`;
    body += text(40, y + 5, label, { size: 23, cls: "muted" });
    body += lines(600, y + 5, value, 540, { size: 22, cls: "mono" });
    y += label.startsWith("Where") ? item.causes.length * 31 + 24 : 62;
  }
  return { height: y + 16, body };
}

