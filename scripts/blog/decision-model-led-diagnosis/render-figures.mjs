function text(x, y, content, { size = 22, cls = "", anchor = "start" } = {}) {
  return `<text x="${x}" y="${y}" font-size="${size}" style="font-size:${size}px" class="${cls}" text-anchor="${anchor}">${esc(content)}</text>`;
}

function wrap(content, width, size) {
  // Conservative Arial text measure; explicit source line breaks stay intact.
  const max = Math.floor(width / (size * 0.54));
  return String(content)
    .split("\n")
    .flatMap((paragraph) => {
      const lines = [];
      let line = "";
      for (const word of paragraph.split(" ")) {
        if (line && line.length + word.length + 1 > max) {
          lines.push(line);
          line = word;
        } else line += (line ? " " : "") + word;
      }
      lines.push(line);
      return lines;
    });
}

function lines(x, y, content, width, opts = {}) {
  const size = opts.size ?? 22;
  return wrap(content, width, size)
    .map((line, i) => text(x, y + i * size * 1.4, line, opts))
    .join("\n");
}

