function table(headers, sections, widths, { size = 21 } = {}) {
  let y = 24;
  let body = "";
  const drawRow = (cells, header = false) => {
    const height =
      Math.max(
        ...cells.map((cell, i) => wrap(cell, widths[i] - 32, size).length),
      ) *
        size *
        1.4 +
      32;
    if (header)
      body += `<rect x="24" y="${y}" width="1152" height="${height}" fill="var(--panel)"/>`;
    let x = 24;
    cells.forEach((cell, i) => {
      let baseline = y + 16 + size;
      String(cell)
        .split("\n")
        .forEach((paragraph, lineIndex) => {
          body += lines(x + 16, baseline, paragraph, widths[i] - 32, {
            size,
            cls: lineIndex > 0 ? "muted" : header || i > 0 ? "bold" : "",
          });
          baseline += wrap(paragraph, widths[i] - 32, size).length * size * 1.4;
        });
      if (i > 0) body += `<path class="rule" d="M${x} ${y}v${height}"/>`;
      x += widths[i];
    });
    y += height;
    body += `<path class="rule" d="M24 ${y}H1176"/>`;
  };
  drawRow(headers, true);
  for (const section of sections) {
    if (section.label) {
      body += `<rect x="24" y="${y}" width="1152" height="52" fill="var(--panel)"/>`;
      body += text(40, y + 34, section.label, { size: 20, cls: "teal bold" });
      y += 52;
      body += `<path class="rule" d="M24 ${y}H1176"/>`;
    }
    section.rows.forEach((row) => drawRow(row));
  }
  body += `<rect x="24" y="24" width="1152" height="${y - 24}" fill="none" class="rule"/>`;
  return { height: Math.ceil(y + 24), body };
}

