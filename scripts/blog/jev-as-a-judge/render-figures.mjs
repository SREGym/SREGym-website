const escape = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");

function label(
  x,
  y,
  value,
  { size = 23, color = "ink", bold = false, anchor = "start" } = {},
) {
  return `<text x="${x}" y="${y}" fill="var(--${color})" font-size="${size}" font-weight="${bold ? 700 : 400}" text-anchor="${anchor}">${escape(value)}</text>`;
}

function wrap(value, width, size) {
  const lines = [];
  let line = "";
  let used = 0;
  for (const word of value.split(" ")) {
    const length =
      [...word].reduce((sum, char) => {
        if (/[ilI1.,':;!|]/.test(char)) return sum + 0.29;
        if (/[MW@%]/.test(char)) return sum + 0.91;
        return sum + (/[A-Z]/.test(char) ? 0.72 : 0.55);
      }, 0) * size;
    if (line && used + 0.32 * size + length > width) {
      lines.push(line);
      line = "";
      used = 0;
    }
    used += length + (line ? 0.32 * size : 0);
    line += (line ? " " : "") + word;
  }
  lines.push(line);
  return lines;
}

function paragraph(x, y, lines, options) {
  return lines
    .map((line, index) =>
      label(x, y + index * Math.round(options.size * 1.36), line, options),
    )
    .join("\n");
}

function box(x, y, width, height, fill = "paper", stroke = "line", radius = 8) {
  return `<rect x="${x}" y="${y}" width="${width}" height="${height}" rx="${radius}" fill="var(--${fill})"${stroke ? ` stroke="var(--${stroke})" stroke-width="1.5"` : ""}/>`;
}

function rule(path, { arrow = false, color = "line", width = 1.5 } = {}) {
  return `<path d="${path}" fill="none" stroke="var(--${color})" stroke-width="${width}" stroke-linejoin="round"${arrow ? ' marker-end="url(#arrow)"' : ""}/>`;
}

const arrow = (path) => rule(path, { arrow: true, color: "muted", width: 2 });

function svg(title, { width, height, body }) {
  return `<!-- Generated by scripts/blog/jev-as-a-judge/render-figures.mjs. -->
<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title">
<title id="title">${escape(title)}</title>
<style>${style}</style>
<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0 0L10 5L0 10Z" fill="var(--muted)"/></marker></defs>
${box(0, 0, width, height, "paper", null, 0)}
${body}
</svg>
`;
}

