function questionRewrite(mobile) {
  const width = mobile ? 440 : 1200;
  const margin = mobile ? 16 : 28;
  const gap = mobile ? 50 : 64;
  const panelWidth = mobile
    ? width - 2 * margin
    : (width - 2 * margin - gap) / 2;
  const size = mobile ? 20 : 23;
  const panels = rewrite.map((item) => {
    let y = 0;
    let body = box(0, 0, panelWidth, 64, item.fill, null);
    body += label(18, 26, "D2-Q2", { size: 14, color: item.color, bold: true });
    body += label(18, 51, item.title, {
      size: mobile ? 24 : 26,
      color: item.color,
      bold: true,
    });
    y += 64;
    for (const [value, color, bold] of [
      [item.key, "muted", true],
      [item.question, "ink", false],
    ]) {
      const lines = wrap(value, panelWidth - 36, size);
      body += rule(`M0 ${y}h${panelWidth}`);
      body += paragraph(18, y + 30, lines, { size, color, bold });
      y += lines.length * Math.round(size * 1.36) + 22;
    }
    for (const [tag, value, color] of item.notes) {
      const lines = wrap(value, panelWidth - 36, size);
      body += rule(`M0 ${y}h${panelWidth}`);
      body += label(18, y + 24, tag, { size: size - 2, color, bold: true });
      body += paragraph(18, y + 52, lines, { size });
      y += lines.length * Math.round(size * 1.36) + 44;
    }
    return { body, height: y };
  });
  const height = mobile
    ? panels[0].height + panels[1].height + gap
    : Math.max(...panels.map((panel) => panel.height));
  const body =
    panels
      .map((panel, index) => {
        const x = mobile ? margin : margin + index * (panelWidth + gap);
        const y =
          mobile && index === 1 ? margin + panels[0].height + gap : margin;
        return `<g transform="translate(${x} ${y})">${box(0, 0, panelWidth, mobile ? panel.height : height)}${panel.body}</g>`;
      })
      .join("\n") +
    (mobile
      ? arrow(`M220 ${margin + panels[0].height + 8}v${gap - 16}`)
      : arrow(`M${margin + panelWidth + 8} ${margin + 150}h${gap - 16}`));
  return { width, height: height + 2 * margin, body };
}

