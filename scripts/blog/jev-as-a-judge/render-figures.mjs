function checklist(mobile) {
  const width = mobile ? 440 : 1200;
  const margin = mobile ? 16 : 28;
  const gap = 16;
  const size = mobile ? 19 : 22;
  const inner = width - 2 * margin;
  const panelWidth = mobile ? inner : (inner - 2 * gap) / 3;
  const questions = dimensions.map((d) =>
    d.questions.map((q) => wrap(q, panelWidth - 70, size)),
  );
  const rowHeight = (count) => count * Math.round(size * 1.36) + 22;
  const sharedRows = questions[0].map((_, i) =>
    Math.max(...questions.map((group) => rowHeight(group[i].length))),
  );
  let body = "";
  let y = margin;
  for (const [i, { name, weight, color }] of dimensions.entries()) {
    const x = mobile ? margin : margin + i * (panelWidth + gap);
    const heights = mobile
      ? questions[i].map((q) => rowHeight(q.length))
      : sharedRows;
    const header = 74;
    const panelHeight =
      header + heights.reduce((sum, height) => sum + height, 0);
    body += box(x, y, panelWidth, panelHeight);
    body += box(x, y, panelWidth, header, `${color}-bg`, null);
    body += label(x + 16, y + 26, `DIMENSION ${i + 1} (D${i + 1})`, {
      size: 15,
      color,
      bold: true,
    });
    body += label(x + panelWidth - 16, y + 26, `Weight ${weight}`, {
      size: 16,
      color,
      anchor: "end",
    });
    body += label(x + 16, y + 55, name, {
      size: mobile ? 23 : 25,
      color,
      bold: true,
    });
    let rowY = y + header;
    for (const [j, lines] of questions[i].entries()) {
      body += rule(`M${x} ${rowY}h${panelWidth}`);
      body += box(x + 15, rowY + 13, 34, 26, `${color}-bg`, null, 5);
      body += label(x + 32, rowY + 32, `Q${j + 1}`, {
        size: 15,
        color,
        bold: true,
        anchor: "middle",
      });
      body += paragraph(x + 59, rowY + 32, lines, { size });
      rowY += heights[j];
    }
    if (mobile || i === dimensions.length - 1) y += panelHeight + gap;
  }
  const scoring =
    "Each dimension is the fraction of its three questions answered Yes.";
  const summaryHeight = mobile ? 153 : 106;
  body += box(margin, y, inner, summaryHeight, "panel");
  body += label(margin + 17, y + 30, "Score", { size, bold: true });
  body += label(
    margin + (mobile ? 17 : 94),
    y + (mobile ? 59 : 30),
    "0.33 × D1 + 0.33 × D2 + 0.34 × D3",
    { size, bold: true },
  );
  body += label(
    width - margin - 17,
    y + (mobile ? 132 : 30),
    "Pass if score ≥ 0.70",
    { size, color: "green", bold: true, anchor: "end" },
  );
  body += paragraph(
    margin + 17,
    y + (mobile ? 86 : 73),
    wrap(scoring, inner - 34, size - 2),
    { size: size - 2, color: "muted" },
  );
  return { width, height: y + summaryHeight + margin, body };
}

